"""Render the shared HTTPS user guide (https-guide.md) for one application.

The guide is a Jinja2 template. An application supplies its values (product name, ports, and so on) and its own
sections, in one of two forms. See integrating-the-https-guide.md.

- An application page: a Markdown file whose front matter holds the values under "https_guide" and whose sections are
  merged into the guide by their headings. This is the recommended form.
- A values file: YAML or JSON, with custom sections as text.

Command line (a .md input is an application page, anything else a values file):
    python render_https_guide.py INPUT --output PAGE [--check]

From an MkDocs hook, which is given the page without its front matter:
    from render_https_guide import merge_page
    markdown = merge_page(page.meta["https_guide"], markdown)

Needs Jinja2, which MkDocs already installs. A YAML values file also needs PyYAML (also installed with MkDocs).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import jinja2

TEMPLATE = Path(__file__).with_name("https-guide.md")
WELL_KNOWN = ".well-known/gameshowpro/"
GATES = ("loopback", "boot", "button")
SECTIONS = ("after_intro", "addresses", "setup", "notes", "keys", "own_certificate", "settings", "extra", "troubleshooting", "end")
# In an application page, a section with one of these headings is merged into the guide's section of the same name.
PAGE_HEADINGS = {
    "Addresses": "addresses",
    "Set up a computer or phone": "setup",
    "What to know": "notes",
    "Where the keys are kept": "keys",
    "Use your own certificate": "own_certificate",
    "Settings": "settings",
    "If it does not work": "troubleshooting",
}
META_KEY = "https_guide"
REPOSITORY_ONLY = re.compile(r"<!--\s*repository-only\s*-->.*?<!--\s*/repository-only\s*-->[ \t]*\n?", re.S)
HEADING = re.compile(r"^(#{1,2})[ \t]+(.*?)(?:[ \t]*\{[^}]*\})?[ \t]*$")
NOTICE = "<!-- Generated from the GameshowPro.TlsCa HTTPS guide. Do not edit this file: change {source} and render again. -->\n\n"

# Values every build has; a build inherits a missing one from the top level, then from here.
BUILD_DEFAULTS = {
    "name": None,
    "host_term": "computer",
    "http_port": None,
    "https_port": None,
    "name_pattern": None,
    "name_example": None,
    "gate": "loopback",
    "auto_renew": True,
    "local_access": True,
    "http_redirects": True,
    "own_certificate": False,
    "storage": [],
}
TOP_DEFAULTS = {
    "title": "Secure access (HTTPS)",
    "ui_name": "web page",
    "reason": None,
    "renew_days": 90,
    "settings_prefix": None,
    "links": {},
    "unverified": [],
    "heading_offset": 0,
}
REQUIRED_BUILD = ("http_port", "https_port", "name_pattern", "name_example")


class GuideError(ValueError):
    """The values file is missing something or holds a value the guide cannot use."""


def load_values(path):
    """Read a YAML or JSON values file. Section entries given as {file: name} are read relative to it."""
    path = Path(path)
    text = path.read_text(encoding="utf-8")
    if path.suffix.lower() == ".json":
        values = json.loads(text)
    else:
        import yaml  # Imported here so a JSON values file needs no PyYAML.

        values = yaml.safe_load(text)
    if not isinstance(values, dict):
        raise GuideError(f"{path}: expected a mapping of values.")
    sections = values.get("sections") or {}
    for name, body in list(sections.items()):
        if isinstance(body, dict):
            if set(body) != {"file"}:
                raise GuideError(f"{path}: section '{name}' must be text or {{file: <path>}}.")
            sections[name] = (path.parent / body["file"]).read_text(encoding="utf-8")
    values["sections"] = sections
    return values


def _origin(scheme, host, port):
    default = 80 if scheme == "http" else 443
    return f"{scheme}://{host}/" if int(port) == default else f"{scheme}://{host}:{port}/"


def _builds(values):
    raw = values.get("builds")
    if raw is None:
        raw = [{}]
    if not isinstance(raw, list) or not raw:
        raise GuideError("'builds' must be a list with at least one build.")
    builds = []
    for index, entry in enumerate(raw):
        build = {key: entry.get(key, values.get(key, default)) for key, default in BUILD_DEFAULTS.items()}
        label = build["name"] or f"build {index + 1}"
        for key in REQUIRED_BUILD:
            if build[key] in (None, ""):
                raise GuideError(f"{label}: '{key}' is required (on the build or at the top level).")
        if build["gate"] not in GATES:
            raise GuideError(f"{label}: 'gate' must be one of {', '.join(GATES)}.")
        if len(raw) > 1 and not build["name"]:
            raise GuideError(f"Build {index + 1} needs a 'name', because there is more than one build.")
        if isinstance(build["storage"], str):
            build["storage"] = [{"where": None, "path": build["storage"]}]
        build["page_any"] = _origin("http", "<host>", build["http_port"]) + WELL_KNOWN
        build["http_any"] = _origin("http", "<host>", build["http_port"])
        build["page_local"] = _origin("http", "localhost", build["http_port"]) + WELL_KNOWN
        build["http_local"] = _origin("http", "localhost", build["http_port"])
        build["secure"] = _origin("https", build["name_pattern"], build["https_port"])
        build["secure_example"] = _origin("https", build["name_example"], build["https_port"])
        builds.append(build)
    return builds


def _shift_headings(text, offset):
    """Move every heading outside fenced code blocks down by offset levels."""
    if not offset:
        return text
    out, in_fence = [], False
    for line in text.split("\n"):
        if line.lstrip().startswith(("```", "~~~")):
            in_fence = not in_fence
        elif not in_fence and line.startswith("#"):
            line = "#" * offset + line
        out.append(line)
    return "\n".join(out)


def render(values, source="the values file", literal_sections=False):
    """Render the guide for one application's values and return the Markdown.

    source names the file to change, for the notice at the top; None leaves the notice out. Custom sections are
    rendered as templates with the same values unless literal_sections is set.
    """
    unknown = set(values) - set(TOP_DEFAULTS) - set(BUILD_DEFAULTS) - {"product", "builds", "sections"}
    if unknown:
        raise GuideError(f"Unknown value(s): {', '.join(sorted(unknown))}.")
    if not values.get("product"):
        raise GuideError("'product' is required.")
    sections = values.get("sections") or {}
    unknown = set(sections) - set(SECTIONS)
    if unknown:
        raise GuideError(f"Unknown section(s): {', '.join(sorted(unknown))}. Known: {', '.join(SECTIONS)}.")
    builds = _builds(values)
    own = [b for b in builds if b["own_certificate"]]
    if own and not values.get("settings_prefix"):
        raise GuideError("'settings_prefix' is required when a build has 'own_certificate'.")
    context = {key: values.get(key, default) for key, default in TOP_DEFAULTS.items()}
    context.update(
        product=values["product"],
        builds=builds,
        single=builds[0] if len(builds) == 1 else None,
        gates=[gate for gate in GATES if any(b["gate"] == gate for b in builds)],
        well_known="/" + WELL_KNOWN,
        _origin_own=_origin("https", "<name in your certificate>", own[0]["https_port"]) if own else None,
    )
    environment = jinja2.Environment(
        undefined=jinja2.StrictUndefined, trim_blocks=True, lstrip_blocks=True, keep_trailing_newline=True, autoescape=False
    )
    # Custom sections are templates too, so they can use the same values.
    context["sections"] = {
        name: (body if literal_sections else environment.from_string(body).render(context)).strip()
        for name, body in sections.items()
        if body and body.strip()
    }
    try:
        text = environment.from_string(TEMPLATE.read_text(encoding="utf-8")).render(context)
    except jinja2.UndefinedError as error:
        raise GuideError(f"The guide uses a value that was not supplied: {error.message}") from error
    text = re.sub(r"\n{3,}", "\n\n", text).strip() + "\n"
    text = _shift_headings(text, int(context["heading_offset"]))
    return NOTICE.format(source=source) + text if source else text


def render_file(path):
    """Render the guide from a values file, or from an application page when the file is Markdown."""
    path = Path(path)
    if path.suffix.lower() == ".md":
        values, body = split_front_matter(path.read_text(encoding="utf-8"), path)
        return merge_page(values, body, path.name)
    return render(load_values(path), path.name)


def split_front_matter(text, path="the page"):
    """Split an application page into its values (front matter key "https_guide") and its Markdown body."""
    import yaml

    match = re.match(r"^---[ \t]*\n(.*?)\n---[ \t]*\n?(.*)$", text, re.S)
    meta = yaml.safe_load(match.group(1)) if match else None
    if not isinstance(meta, dict) or not isinstance(meta.get(META_KEY), dict):
        raise GuideError(f"{path}: the front matter needs a '{META_KEY}' mapping with the application's values.")
    return meta[META_KEY], match.group(2)


def split_page(body):
    """Split an application page's body into its title and its sections, keyed as the guide's custom sections.

    Text before the first second-level heading is the 'after_intro' section. A second-level heading named in
    PAGE_HEADINGS gives the body for that guide section. Any other second-level section is kept whole, heading
    included: in 'extra' (before "If it does not work") or, when it comes after that heading in the page, in 'end'.
    """
    body = REPOSITORY_ONLY.sub("", body)
    title, parts, current, in_fence, after_troubleshooting = None, {}, "after_intro", False, False
    for line in body.split("\n"):
        if line.lstrip().startswith(("```", "~~~")):
            in_fence = not in_fence
        match = None if in_fence else HEADING.match(line)
        if match and match.group(1) == "#":
            if title is not None:
                raise GuideError("The page has more than one first-level heading.")
            title = match.group(2)
            continue
        if match:
            name = PAGE_HEADINGS.get(match.group(2))
            if name is None:
                current = "end" if after_troubleshooting else "extra"
                parts.setdefault(current, []).append(line)
                continue
            if name in parts:
                raise GuideError(f"The page has two '{match.group(2)}' sections.")
            after_troubleshooting = after_troubleshooting or name == "troubleshooting"
            current = name
            parts[current] = []
            continue
        parts.setdefault(current, []).append(line)
    return title, {name: "\n".join(lines).strip() for name, lines in parts.items()}


def merge_page(values, body, source=None):
    """Merge an application page into the guide: values from its front matter, sections from its headings.

    The page's own text is not treated as a template, so it may hold braces. Its first-level heading, when it has one,
    is the title.
    """
    values = dict(values)
    if values.get("sections"):
        raise GuideError("An application page gives its sections as headings, not under 'sections'.")
    title, sections = split_page(body)
    if title:
        values["title"] = title
    values["sections"] = sections
    return render(values, source, literal_sections=True)


def main(argv=None):
    parser = argparse.ArgumentParser(description="Render the shared HTTPS user guide for one application.")
    parser.add_argument("values", metavar="INPUT", help="The application page (.md), or a YAML or JSON values file.")
    parser.add_argument("--output", "-o", required=True, help="The Markdown page to write.")
    parser.add_argument("--check", action="store_true", help="Write nothing; fail when the page is missing or out of date.")
    arguments = parser.parse_args(argv)
    try:
        text = render_file(arguments.values)
    except (GuideError, OSError) as error:
        print(f"render_https_guide: {error}", file=sys.stderr)
        return 2
    output = Path(arguments.output)
    current = output.read_text(encoding="utf-8") if output.exists() else None
    if arguments.check:
        if current != text:
            print(f"render_https_guide: {output} is out of date; render it again.", file=sys.stderr)
            return 1
        return 0
    if current != text:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
